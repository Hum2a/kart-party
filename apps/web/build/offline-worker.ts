import { createHash } from "node:crypto";
import { readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import type { Plugin } from "vite";

/** Every file under `public/`, as site paths. */
function publicFiles(dir: string, root = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory()
      ? publicFiles(path, root)
      : ["/" + relative(root, path).split("\\").join("/")];
  });
}

/**
 * The worker that lets an installed Kart Party open and run practice offline.
 * Pages come from the network first, so an online visit always gets the latest
 * build; built files are content-hashed, so they are served from the cache.
 * The room API and sockets are never cached.
 */
export function offlineWorkerSource(version: string, precache: readonly string[]) {
  return `// Generated by apps/web/build/offline-worker.ts. Do not edit.
const CACHE = "kart-party-${version}";
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith("kart-party-") && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith("/api")) return;
  if (request.mode === "navigate") {
    // Every route is the same single page.
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put("/", copy));
          }
          return response;
        })
        .catch(() => caches.match("/", { cacheName: CACHE }).then((hit) => hit || Response.error())),
    );
    return;
  }
  // Built files are content-hashed, so Vary (the server sends Vary: Origin, and
  // module scripts carry an Origin header the precache requests did not) is safe to ignore.
  event.respondWith(
    caches.match(request, { ignoreVary: true }).then(
      (hit) =>
        hit ||
        fetch(request).then((response) => {
          if (response.ok && url.pathname.startsWith("/assets/")) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;
}

/** Emits /sw.js with the client build's files, in production builds only. */
export function offlineWorker(publicDir: string): Plugin {
  return {
    name: "kart-party-offline-worker",
    apply: "build",
    applyToEnvironment: (environment) => environment.name === "client",
    generateBundle(_options, bundle) {
      const built = Object.keys(bundle)
        .filter(
          (file) =>
            file !== "index.html" &&
            file !== "sw.js" &&
            !file.endsWith(".map") &&
            !file.startsWith(".") &&
            !file.endsWith(".json"),
        )
        .map((file) => "/" + file);
      const precache = [
        "/",
        ...publicFiles(publicDir).filter((file) => file !== "/sw.js"),
        ...built,
      ].sort();
      const version = createHash("sha256")
        .update(precache.join("\n"))
        .digest("hex")
        .slice(0, 12);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: offlineWorkerSource(version, precache),
      });
    },
  };
}
